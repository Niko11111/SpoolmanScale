# -*- coding: utf-8 -*-
# ============================================================
#  SpoolmanScale – Localization (i18n)
#  gen_zh_fonts.py - Simplified Chinese (zh-CN) glyph supplement generator
#  简体中文（zh-CN）UI 字体补充库生成脚本
#
#  Fallback chain / 字体回退链:
#    lv_font_montserrat_ext_NN -> lv_font_fr_supp_NN -> lv_font_zh_supp_NN
#
#  Font source / 字体来源:
#    Noto Sans SC (NotoSansSC-Medium.otf, SIL Open Font License 1.1)
#    Download / 下载地址:
#      https://github.com/notofonts/noto-cjk/tree/main/Sans/SubsetOTF/SC
#      (Get static NotoSansSC-Medium.otf; do NOT use Variable or Serif fonts.)
#      （请下载静态字体 NotoSansSC-Medium.otf，勿使用可变字体或 Serif 宋体。）
#    Placement / 存放位置:
#      Place anywhere locally (e.g. tools/NotoSansSC-Medium.otf) and pass via --font.
#      Do NOT commit the .otf file to git (already ~8 MB; only generated .c files belong in repo).
#      可放于本地任意目录（如 tools/NotoSansSC-Medium.otf）并通过 --font 指定；
#      请勿将 .otf 源文件提交进 Git 仓库（仅需提交生成的 .c 字库文件）。
#    Note: Requires LV_USE_FONT_COMPRESSED 1 in src/lv_conf.h.
#    注意：需在 src/lv_conf.h 中启用 LV_USE_FONT_COMPRESSED 1。
#
#  Glyph & compression strategy / 字集与压缩策略:
#    - 14, 16, 18 px (lists / body / backend data | 列表 / 正文 / 后端动态数据):
#        GB2312 Level-1 (3,755 common Hanzi) + CJK punctuation + all chars in lang_zh.jsonl
#        GB2312 一级常用汉字（3755 字）+ 中文标点 + lang_zh.jsonl 全部字符
#        Built with --bpp 2 (compressed) to keep flash footprint compact.
#        采用 --bpp 2 压缩格式，以控制 Flash 占用。
#    - 10, 12, 20, 24 px (small captions / headers | 小号标注 / 标题):
#        All chars in lang_zh.jsonl + CJK punctuation + "中文"
#        仅包含 lang_zh.jsonl 用字 + 中文标点 + "中文"
#        Built with --bpp 4 (compressed) for sharper rendering.
#        采用 --bpp 4 压缩格式，保证大小字号清晰度。
#
#  Usage / 用法:
#    python tools/gen_zh_fonts.py --font path/to/NotoSansSC-Medium.otf --build
#    python tools/gen_zh_fonts.py --wire
#    python tools/gen_zh_fonts.py --font path/to/NotoSansSC-Medium.otf --all
# ============================================================
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "src" / "fonts"
LV_CONF = ROOT / "src" / "lv_conf.h"
WORK_ZH = ROOT / "tools" / "lang_zh.jsonl"

SIZES = (10, 12, 14, 16, 18, 20, 24)
# Sizes that render dynamic backend data (spool names, vendors, locations, Bambu colors)
FULL_SIZES = {14, 16, 18}

HOST = "lv_font_montserrat_ext_%d"
FR_SUPP = "lv_font_fr_supp_%d"
ZH_SUPP = "lv_font_zh_supp_%d"

LF = chr(10)

# Common CJK punctuation + button label "中文"
BASE_EXTRA_CHARS = (
    "中文"
    "，。、：；！？（）【】《》“”‘’·…—～－＋×÷℃"
)

BANNER = """\
/*******************************************************************************
 * SpoolmanScale - Chinese glyph supplement for %(host)s
 *
 * Generated by tools/gen_zh_fonts.py. Do not edit by hand.
 *
 * Reached through %(fr_supp)s's .fallback, so the host font's line_height and
 * base_line remain completely untouched for DE / EN / FR.
 ******************************************************************************/
"""


def write_lf(path, text):
    with open(path, "w", encoding="utf-8", newline=LF) as f:
        f.write(text)


def gb2312_level1_chars():
    """All 3755 GB2312 Level-1 common Simplified Chinese characters (sections 16..55)."""
    chars = []
    for area in range(16, 56):
        for pos in range(1, 95):
            if area == 55 and pos >= 90:
                continue
            b = bytes([area + 0xA0, pos + 0xA0])
            try:
                chars.append(b.decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return "".join(chars)


def ui_zh_chars():
    """Collect every non-ASCII character used in tools/lang_zh.jsonl."""
    chars = set(BASE_EXTRA_CHARS)
    if WORK_ZH.exists():
        for line in WORK_ZH.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            zh = rec.get("zh") or ""
            # Strip {LV_SYMBOL_...} macros and \n escapes
            zh = re.sub(r"\{[A-Za-z_]\w*\}", "", zh).replace("\\n", "")
            for ch in zh:
                if ord(ch) > 0x7F:
                    chars.add(ch)
    return "".join(sorted(chars))


def chars_to_ranges(chars_str):
    """Compress sorted unique characters into lv_font_conv -r hex ranges."""
    cps = sorted({ord(c) for c in chars_str if ord(c) > 0x7F})
    if not cps:
        return ""
    ranges = []
    start = prev = cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp
        else:
            ranges.append("0x%X" % start if start == prev else "0x%X-0x%X" % (start, prev))
            start = prev = cp
    ranges.append("0x%X" % start if start == prev else "0x%X-0x%X" % (start, prev))
    return ",".join(ranges)


def resolve_lv_font_conv():
    """Return command prefix to run lv_font_conv directly via real node.exe."""
    exe = shutil.which("lv_font_conv.cmd") or shutil.which("lv_font_conv")
    if not exe:
        return None
    p = pathlib.Path(exe)
    if p.suffix.lower() in (".cmd", ".bat"):
        js = p.parent / "node_modules" / "lv_font_conv" / "lv_font_conv.js"
        if not js.exists():
            m = re.search(r'"%dp0%\\([^"]+lv_font_conv\.js)"',
                          p.read_text(encoding="utf-8", errors="replace"), re.I)
            if m:
                js = p.parent / m.group(1)
        if js.exists():
            # Prefer the real node.exe next to node_modules (bypasses ServBay/nvm shims)
            real_node = js.parent.parent.parent / "node.exe"
            node = str(real_node) if real_node.exists() else shutil.which("node")
            if node:
                return [node, str(js)]
    return [exe]


def resolve_font_path(user_font):
    if user_font:
        p = pathlib.Path(user_font)
        if not p.exists():
            print("Font file not found: %s" % p)
            return None
        return p
    # Auto-search common places in repo or Windows Fonts
    candidates = [
        ROOT / "tools" / "NotoSansSC-Medium.otf",
        ROOT / "tools" / "NotoSansSC-Medium.ttf",
        ROOT / "tools" / "NotoSansSC-Regular.ttf",
        ROOT / "tools" / "HarmonyOS_Sans_SC_Medium.ttf",
        ROOT / "tools" / "HarmonyOS_Sans_SC_Regular.ttf",
        pathlib.Path("C:/Windows/Fonts/simhei.ttf"),
    ]
    for c in candidates:
        if c.exists():
            return c
    print("No Chinese TTF/OTF font found.")
    print("Please download NotoSansSC-Medium.ttf (or HarmonyOS_Sans_SC_Medium.ttf)")
    print("into tools/ or pass it with --font <path>.")
    return None


def build(font_path, full_bpp=2, ui_bpp=4):
    cmd_prefix = resolve_lv_font_conv()
    if not cmd_prefix:
        print("lv_font_conv not found. Install it with:")
        print("  npm i -g lv_font_conv@1.5.3")
        return False

    ttf = resolve_font_path(font_path)
    if not ttf:
        return False

    ui_chars = ui_zh_chars()
    full_chars = "".join(sorted(set(ui_chars) | set(gb2312_level1_chars())))
    ui_range = chars_to_ranges(ui_chars)
    full_range = chars_to_ranges(full_chars)

    print("== building %d Chinese supplements ==" % len(SIZES))
    print("   runner    : %s" % " ".join(cmd_prefix))
    print("   font      : %s" % ttf)
    print("   UI set    : %d unique chars (sizes: %s, bpp=%d)"
          % (len(ui_chars), [s for s in SIZES if s not in FULL_SIZES], ui_bpp))
    print("   Full set  : %d unique chars (sizes: %s, bpp=%d)"
          % (len(full_chars), sorted(FULL_SIZES), full_bpp))

    total_bytes = 0
    for size in SIZES:
        is_full = size in FULL_SIZES
        bpp = full_bpp if is_full else ui_bpp
        chars = full_chars if is_full else ui_chars
        rng = full_range if is_full else ui_range
        out = FONTS / ("%s.c" % (ZH_SUPP % size))

        # Short sets use -r hex ranges; large non-contiguous sets use --symbols
        # (3781 chars vs ~24,000 chars for -r, safely under Windows limits).
        glyph_args = ["-r", rng] if len(rng) <= 2000 else ["--symbols", chars]

        cmd = cmd_prefix + [
            "--bpp", str(bpp),
            "--size", str(size),
            "--font", str(ttf),
        ] + glyph_args + [
            "--no-kerning",
            "--format", "lvgl",
            "-o", str(out),
        ]
        r = subprocess.run(cmd, capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
        if r.returncode != 0:
            print("  size %-3d FAILED\n%s\n%s" % (size, r.stdout, r.stderr))
            return False

        src = out.read_text(encoding="utf-8")
        src = src.replace('#include "lvgl/lvgl.h"', '#include "lvgl.h"')
        if "******/" in src:
            end = src.index("******/") + len("******/")
            src = BANNER % {"host": HOST % size, "fr_supp": FR_SUPP % size} + src[end:]
        write_lf(out, src)

        sz = out.stat().st_size
        total_bytes += sz
        print("  size %-3d %-28s bpp=%d  (%s, %.1f KB source)"
              % (size, out.name, bpp, "GB2312+UI" if is_full else "UI-only", sz / 1024.0))

    print("  done. Total generated .c size: %.1f KB (compiled flash size will be much smaller)"
          % (total_bytes / 1024.0))
    return True


def wire():
    """Chain lv_font_fr_supp_NN -> lv_font_zh_supp_NN and declare in lv_conf.h."""
    print("== wiring Chinese fallback chain ==")
    for size in SIZES:
        fr_file = FONTS / ("%s.c" % (FR_SUPP % size))
        if not fr_file.exists():
            print("  size %-3d MISSING %s" % (size, fr_file.name))
            return False
        want = "    .fallback = &%s," % (ZH_SUPP % size)
        src = fr_file.read_text(encoding="utf-8")
        if want in src:
            print("  size %-3d already wired" % size)
            continue
        if "    .fallback = NULL," not in src:
            print("  size %-3d NO '.fallback = NULL,' line in %s" % (size, fr_file.name))
            return False
        src = src.replace("    .fallback = NULL,", want, 1)
        write_lf(fr_file, src)
        print("  size %-3d %s -> %s" % (size, FR_SUPP % size, ZH_SUPP % size))

    conf = LV_CONF.read_text(encoding="utf-8")
    if ZH_SUPP % SIZES[0] in conf:
        print("  lv_conf.h already declares Chinese supplements")
        return True
    anchor = "    LV_FONT_DECLARE(lv_font_fr_supp_24)"
    if anchor not in conf:
        print("  lv_conf.h: anchor '%s' not found" % anchor)
        return False
    added = anchor + "  \\\n" + "".join(
        "    LV_FONT_DECLARE(%s)%s\n" % (
            ZH_SUPP % s, "  \\" if s != SIZES[-1] else "")
        for s in SIZES).rstrip("\n")
    conf = conf.replace(anchor, added, 1)
    write_lf(LV_CONF, conf)
    print("  lv_conf.h: %d Chinese supplements declared" % len(SIZES))
    return True


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="Generate & wire Chinese LVGL supplement fonts.")
    ap.add_argument("--font", metavar="PATH", help="Path to Chinese TTF/OTF font file")
    ap.add_argument("--full-bpp", type=int, default=2, choices=(1, 2, 4),
                    help="BPP for 14/16/18px GB2312 fonts (default: 2)")
    ap.add_argument("--ui-bpp", type=int, default=4, choices=(1, 2, 4),
                    help="BPP for 10/12/20/24px UI-only fonts (default: 4)")
    ap.add_argument("--build", action="store_true", help="Generate the 7 zh supplement .c files")
    ap.add_argument("--wire", action="store_true", help="Wire .fallback in fr_supp and lv_conf.h")
    ap.add_argument("--all", action="store_true", help="Run --build then --wire")
    a = ap.parse_args()

    if not (a.build or a.wire or a.all):
        ap.print_help()
        return 2
    if a.all or a.build:
        if not build(a.font, a.full_bpp, a.ui_bpp):
            return 1
        print()
    if a.all or a.wire:
        if not wire():
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())