#!/usr/bin/env python3
"""Write src/services/spool_catalog_data.h: the empty spools of SpoolmanDB, one row per kind.

A user who winds a refill onto another maker's spool, or whose maker sells
several spools, picks the empty spool on the scale (Options > Empty spool >
Makers). This builds that list from SpoolmanDB's filaments: one entry per
maker, spool type and empty weight, the most common first, with the net
weight it usually carries.

The input is SpoolmanDB's filament list as a JSON array, either from a
Spoolman server (GET /api/v1/external/filament) or from the database's
release (filaments.json at https://donkie.github.io/SpoolmanDB/). SpoolmanDB
is MIT licensed; its notice goes into the generated file.

Run before a release and commit the header with the change that needs it:

    curl -s http://<spoolman>:7912/api/v1/external/filament > /tmp/sdb.json
    tools/gen_spool_catalog.py /tmp/sdb.json
"""
import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).parents[1]
OUTPUT = ROOT / "src/services/spool_catalog_data.h"
# SpoolmanDB's spool types; the firmware's SpoolKind (services/spool_choice.h)
# numbers them the same way, 0 for an entry that names none.
KINDS = {None: 0, "plastic": 1, "cardboard": 2, "metal": 3}
KIND_NAMES = ["SPOOL_KIND_ANY", "SPOOL_KIND_PLASTIC", "SPOOL_KIND_CARDBOARD", "SPOOL_KIND_METAL"]
# The firmware keeps the name in a char[32] and a maker's spools in a uint8_t.
NAME_MAX = 31
MAX_SPOOLS_PER_MAKER = 255

