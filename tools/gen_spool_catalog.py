def spools_by_maker(filaments):
    """{maker: [(kind, weight_g, net_g, count)]}, most common spool first."""
    counts = defaultdict(Counter)    # (maker, kind, weight) -> net weights seen
    for f in filaments:
        weight = f.get("spool_weight") or 0
        maker = (f.get("manufacturer") or "").strip()
        if weight <= 0 or not maker:
            continue
        kind = KINDS.get(f.get("spool_type"), 0)
        counts[(maker, kind, round(weight))][round(f.get("weight") or 0)] += 1
    # An entry that names no type is the same spool as a typed one of that
    # weight: Sunlu's 189 g would show up twice otherwise.
    for (maker, kind, weight) in [k for k in counts if k[1] == 0]:
        typed = [k for k in counts if k[0] == maker and k[2] == weight and k[1] != 0]
        if typed:
            counts[max(typed, key=lambda k: sum(counts[k].values()))] += counts.pop((maker, kind, weight))
    makers = defaultdict(list)
    for (maker, kind, weight), nets in counts.items():
        net, _ = nets.most_common(1)[0]
        makers[maker].append((kind, weight, net, sum(nets.values())))
    for spools in makers.values():
        spools.sort(key=lambda s: (-s[3], s[1]))
    return makers


def check(makers):
    for maker, spools in makers.items():
        if len(maker) > NAME_MAX or not maker.isascii() or '"' in maker or "\\" in maker:
            sys.exit(f"maker name the firmware cannot hold as it is: {maker!r}")
        if len(spools) > MAX_SPOOLS_PER_MAKER:
            sys.exit(f"{maker} has {len(spools)} spools, more than a uint8_t counts")
        for _, weight, net, _ in spools:
            if not 0 < weight < 65536 or not 0 <= net < 65536:
                sys.exit(f"{maker}: a weight outside uint16_t ({weight} g, {net} g)")


def render(makers, source):
    names = sorted(makers, key=str.casefold)
    lines = [
        "#pragma once",
        "",
        f"// Generated by tools/gen_spool_catalog.py from SpoolmanDB ({source}).",
        "// Do not edit: run the script again. Included by services/spool_choice.cpp only.",
        "//",
        LICENSE,
        "",
        '#include "services/spool_choice.h"',
        "",
        "// kind, empty spool g, net filament g: each maker's spools, the most common first.",
        "static const SpoolCatalogSpool SPOOL_CATALOG_SPOOLS[] = {",
    ]
    rows, first = [], 0
    for name in names:
        lines.append(f"  // {name}")
        for kind, weight, net, count in makers[name]:
            lines.append(f"  {{ {KIND_NAMES[kind]}, {weight}, {net} }},   // {count} filaments")
        rows.append((name, first, len(makers[name])))
        first += len(makers[name])
    lines += ["};", "", "// name, first spool, number of spools; by name, ignoring case.",
              "static const SpoolCatalogMaker SPOOL_CATALOG_MAKERS[] = {"]
    lines += [f'  {{ "{name}", {start}, {n} }},' for name, start, n in rows]
    lines += ["};", "",
              f"#define SPOOL_CATALOG_MAKER_COUNT  {len(rows)}",
              f"#define SPOOL_CATALOG_SPOOL_COUNT  {first}", ""]
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    filaments = json.loads(Path(sys.argv[1]).read_text())
    makers = spools_by_maker(filaments)
    check(makers)
    source = f"{len(filaments)} filaments, {date.today().isoformat()}"
    OUTPUT.write_text(render(makers, source))
    total = sum(len(s) for s in makers.values())
    print(f"{OUTPUT.relative_to(ROOT)}: {len(makers)} makers, {total} empty spools")


if __name__ == "__main__":
    main()
